use std::collections::HashSet;

use xidl_parser::hir::{Annotation, OpTypeSpec, TypeSpec};

use crate::catalog::pascal_case;

use super::hir::{annotation_rename, annotation_string, Interface, StructOut};

pub(super) fn emit_dts(server: &str, interfaces: &[Interface], structs: &[StructOut]) -> String {
    let struct_names: HashSet<&str> = structs.iter().map(|decl| decl.name.as_str()).collect();
    let mut out = String::new();
    out.push_str("// Generated by xidl-codemode-glue. Do not edit.\n\n");
    out.push_str("export type CodeModeValue = unknown;\n\n");
    out.push_str("export interface XidlGlueHost {\n  callTool(call: string): string;\n}\n\n");
    out.push_str(
        "export declare function installXidlGlue(target: object, host: XidlGlueHost): void;\n\n",
    );
    for decl in structs {
        out.push_str(&format!("export interface {} {{\n", decl.name));
        for field in &decl.fields {
            let suffix = if field.optional { "?" } else { "" };
            out.push_str(&format!(
                "  {}{}: {};\n",
                field.name,
                suffix,
                ts_type(&field.ty, &struct_names)
            ));
        }
        out.push_str("}\n\n");
    }
    for interface in interfaces {
        let namespace = annotation_string(&interface.annotations, "mcp_namespace")
            .unwrap_or_else(|| "default".to_string());
        out.push_str(&format!("export interface {} {{\n", interface.name));
        for op in &interface.operations {
            let wire_tool_name =
                annotation_rename(&op.annotations).unwrap_or_else(|| op.ident.clone());
            if wire_tool_name != op.ident {
                out.push_str(&format!("  /** MCP tool: {wire_tool_name} */\n"));
            }
            let params_interface_name = format!(
                "{}{}{}Params",
                pascal_case(server),
                pascal_case(&namespace),
                pascal_case(&op.ident)
            );
            let fields = op
                .parameter
                .as_ref()
                .map(|parameters| parameters.0.clone())
                .unwrap_or_default();
            out.push_str(&format!("export interface {params_interface_name} {{\n"));
            for param in &fields {
                let optional = param
                    .annotations
                    .iter()
                    .any(|annotation| matches!(annotation, Annotation::Optional { .. }));
                let suffix = if optional { "?" } else { "" };
                out.push_str(&format!(
                    "  {}{}: {};\n",
                    param.declarator.0,
                    suffix,
                    ts_type(&param.ty, &struct_names)
                ));
            }
            out.push_str("}\n\n");
            let argument = if fields.is_empty() {
                format!("params?: {params_interface_name}")
            } else {
                format!("params: {params_interface_name}")
            };
            let return_type = match &op.ty {
                OpTypeSpec::Void => "void".to_string(),
                OpTypeSpec::TypeSpec(ty) => ts_type(ty, &struct_names),
            };
            out.push_str(&format!("  {}({}): {};\n", op.ident, argument, return_type));
        }
        out.push_str("}\n\n");
    }
    out
}

fn ts_type(ty: &TypeSpec, struct_names: &HashSet<&str>) -> String {
    match ty {
        TypeSpec::ScopedName(name) => {
            let last = name.name.last().map(String::as_str);
            if last.is_some_and(|name| struct_names.contains(name)) {
                last.unwrap().to_string()
            } else {
                match last {
                    Some("string") => "string".to_string(),
                    Some("boolean") => "boolean".to_string(),
                    _ => "unknown".to_string(),
                }
            }
        }
        TypeSpec::SequenceType(sequence) => {
            format!("Array<{}>", ts_type(&sequence.ty, struct_names))
        }
        TypeSpec::MapType(map) => {
            format!("Record<string, {}>", ts_type(&map.value, struct_names))
        }
        TypeSpec::StringType(_) | TypeSpec::WideStringType(_) => "string".to_string(),
        TypeSpec::Boolean => "boolean".to_string(),
        TypeSpec::AnyType => "CodeModeValue".to_string(),
        TypeSpec::IntegerType(_) => "number".to_string(),
        TypeSpec::FloatingPtType => "number".to_string(),
        _ => "unknown".to_string(),
    }
}
